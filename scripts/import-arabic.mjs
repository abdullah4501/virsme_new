import { writeFile } from "node:fs/promises";
// Transcription of the supplied Arabic sections. Missing sections are tracked separately.
async function page(name, hero, intro, source, eyebrow = "") {
  const blocks = source
    .trim()
    .split("\n")
    .filter(Boolean)
    .map((line) => {
      const prefix = line.slice(0, 2),
        text = line.slice(2);
      return {
        kind:
          prefix === "# "
            ? "heading"
            : prefix === "> "
              ? "cta"
              : prefix === "~ "
                ? "message"
                : prefix === "! "
                  ? "trust"
                  : prefix === "* "
                    ? "list"
                    : "text",
        text: prefix === "* " ? "" : text,
        items: prefix === "* " ? text.split("|") : [],
      };
    });
  await writeFile(
    `src/content/${name}/ar.json`,
    JSON.stringify(
      {
        title: `VirSME | ${hero}`,
        description: intro,
        eyebrow,
        hero,
        intro,
        blocks,
      },
      null,
      2,
    ) + "\n",
  );
}
